"""Package Letter Smash as a self-contained HTML file."""

import argparse
import base64
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "letter-smash.html"
MODULES = ("game.js", "examples.js", "speech.js")
SVG_REFERENCE = re.compile(r'"(art/[\w-]+\.svg)"')


def read(path):
    return (ROOT / path).read_text(encoding="utf-8")


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise ValueError(f"Expected exactly one {old!r} in the source.")
    return text.replace(old, new, 1)


def data_url(path, media_type):
    encoded = base64.b64encode(read(path).encode("utf-8")).decode("ascii")
    return f"data:{media_type};base64,{encoded}"


def embed_svgs(text):
    return SVG_REFERENCE.sub(lambda match: f'"{data_url(match[1], "image/svg+xml")}"', text)


def build():
    html = read("index.html").replace('href="art/icons.svg#', 'href="#')
    styles = embed_svgs(read("styles.css")).rstrip()
    entry = read("app.js").rstrip()
    if re.search(r"</style\b", styles, re.IGNORECASE) or re.search(r"</script\b", entry, re.IGNORECASE):
        raise ValueError("Source contains a closing HTML tag that would break the inline CSS or JavaScript.")

    imports = json.dumps({"imports": {f"./{path}": data_url(path, "text/javascript") for path in MODULES}}, indent=2)
    html = replace_once(html, '<link rel="stylesheet" href="styles.css">', f"<style>\n{styles}\n  </style>")
    html = replace_once(
        html,
        '<script src="app.js" type="module"></script>',
        f'<script type="importmap">\n{imports}\n  </script>\n  <script type="module">\n{entry}\n  </script>',
    )
    icons = replace_once(
        read("art/icons.svg").rstrip(),
        '<svg xmlns="http://www.w3.org/2000/svg">',
        '<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" aria-hidden="true" style="position:absolute">',
    )
    html = replace_once(html, '<body data-theme="space">', f'<body data-theme="space">\n  {icons}')
    html = replace_once(html, "<!doctype html>", "<!doctype html>\n<!-- Generated by scripts/build_standalone.py. -->")
    return embed_svgs(html).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the committed HTML is up to date without writing it.")
    args = parser.parse_args()
    try:
        output = build()
        if args.check:
            if not OUTPUT.is_file() or OUTPUT.read_bytes() != output:
                parser.exit(1, "letter-smash.html is missing or out of date. Run scripts/build_standalone.py.\n")
            print("letter-smash.html is up to date.")
        else:
            OUTPUT.write_bytes(output)
            print("Built letter-smash.html.")
    except (OSError, ValueError) as error:
        parser.exit(1, f"Could not build letter-smash.html: {error}\n")


if __name__ == "__main__":
    main()
